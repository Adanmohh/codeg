async page => {
  const dialog = page.getByRole('dialog', {name: 'Shape the customer welcome · Synthetic', exact: true});
  const draft = await dialog.getByLabel('Brief', {exact: true}).inputValue();
  let pending = page.waitForResponse(response => response.url().endsWith('/api/business/tasks/update'));
  await dialog.getByRole('button', {name: 'Save changes', exact: true}).click();
  const conflict = await pending;
  if (conflict.status() !== 409) throw Error('Expected real revision conflict: ' + conflict.status());
  await dialog.getByText('This task changed while you were editing.', {exact: true}).waitFor();
  if (!(await dialog.getByRole('button', {name: 'Save changes', exact: true}).isDisabled()) || await dialog.getByLabel('Brief', {exact: true}).inputValue() !== draft) throw Error('Conflict lost draft or allowed blind save');
  await page.screenshot({path: 'reports/business-workspace-evidence/task-conflict-real.png'});
  await dialog.getByRole('button', {name: 'Load current task', exact: true}).click();
  await dialog.getByRole('heading', {name: 'Current saved version', exact: true}).waitFor();
  await dialog.getByText('Synthetic owner revision: keep the welcome focused on the first useful action.', {exact: true}).waitFor();
  await page.screenshot({path: 'reports/business-workspace-evidence/task-compare-real.png'});
  await dialog.getByRole('button', {name: 'Use my draft with this version', exact: true}).click();
  if (await dialog.getByLabel('Brief', {exact: true}).inputValue() !== draft) throw Error('Explicit adoption lost draft');
  pending = page.waitForResponse(response => response.url().endsWith('/api/business/tasks/update'));
  await dialog.getByRole('button', {name: 'Save changes', exact: true}).click();
  let response = await pending;
  if (response.status() !== 200) throw Error('CAS recovery failed');
  const updated = (await response.json()).task;
  await dialog.getByRole('button', {name: 'Start work', exact: true}).click();
  await dialog.getByText('In progress', {exact: true}).first().waitFor();
  await dialog.getByLabel('Add note', {exact: true}).fill('Synthetic update: the draft is ready for a separate human decision.');
  pending = page.waitForResponse(response => response.url().endsWith('/api/business/tasks/note'));
  await dialog.getByRole('button', {name: 'Add note', exact: true}).click();
  response = await pending;
  if (response.status() !== 200) throw Error('Note failed');
  await dialog.locator('summary').filter({hasText: 'Submit for review'}).click();
  await dialog.getByLabel('Deliverable', {exact: true}).fill('Synthetic deliverable: Welcome to Hafidh. Start with the one task your team needs next. No message was sent.');
  pending = page.waitForResponse(response => response.url().endsWith('/api/business/tasks/submit'));
  await dialog.locator('details').filter({has: page.getByLabel('Deliverable', {exact: true})}).getByRole('button', {name: 'Submit for review', exact: true}).click();
  response = await pending;
  if (response.status() !== 200) throw Error('Submit failed');
  const submitted = await response.json();
  if (submitted.task.status !== 'review' || !submitted.task.currentDeliverableId || await dialog.getByRole('button', {name: 'Accept work', exact: true}).count()) throw Error('Submission bypassed separate reviewer');
  await page.screenshot({path: 'reports/business-workspace-evidence/member-deliverable-real.png'});
  await dialog.getByRole('button', {name: 'Close', exact: true}).click();
  return {synthetic: true, conflictStatus: 409, draftPreserved: true, comparisonRequired: true, savedRevision: updated.revision, dueDate: updated.dueDate, submittedRevision: submitted.task.revision, status: submitted.task.status, currentDeliverableId: submitted.task.currentDeliverableId, noSelfReviewControl: true};
}
