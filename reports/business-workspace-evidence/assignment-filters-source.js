async page => {
  await page.getByRole('button').filter({has:page.getByRole('heading',{name:'Prepare the feedback summary · Synthetic',exact:true})}).click();
  let dialog=page.getByRole('dialog',{name:'Prepare the feedback summary · Synthetic',exact:true});
  await dialog.getByRole('button',{name:'Responsibility',exact:true}).click();
  const unavailable=await dialog.getByLabel('Accountable owner',{exact:true}).locator('option:checked').textContent();
  if(unavailable!=='Member unavailable') throw Error('Revoked owner is still assignable');
  await dialog.getByLabel('Accountable owner',{exact:true}).selectOption({label:'Amal · Synthetic owner'});
  await dialog.getByLabel('Assigned to',{exact:true}).selectOption({label:'Samira · Synthetic manager'});
  await dialog.getByLabel('Reviewer',{exact:true}).selectOption({label:'Amal · Synthetic owner'});
  let pending=page.waitForResponse(r=>r.url().endsWith('/api/business/tasks/assign'));
  await dialog.getByRole('button',{name:'Save changes',exact:true}).click();
  let response=await pending;
  if(response.status()!==200)throw Error('Assignment failed: '+response.status());
  const {task}=await response.json();
  if(task.ownerId===task.assigneeId||task.ownerId!==task.reviewerId)throw Error('Separate responsibility differs');
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  pending=page.waitForResponse(r=>r.url().endsWith('/api/business/tasks/list'));
  await page.getByLabel('Area of work',{exact:true}).selectOption('website');
  response=await pending;
  const website=await response.json();
  if(website.tasks.length!==1||website.tasks[0].domain!=='website')throw Error('Area filtering is not real');
  await page.getByRole('button').filter({has:page.getByRole('heading',{name:'Check the homepage promise · Synthetic',exact:true})}).click();
  dialog=page.getByRole('dialog',{name:'Check the homepage promise · Synthetic',exact:true});
  await dialog.locator('summary').filter({hasText:'Engineering detail'}).click();
  if(await dialog.getByRole('button',{name:'Authorize this execution source',exact:true}).count())throw Error('Personal owner got operator entrustment');
  await dialog.getByLabel('Existing engineering task number',{exact:true}).fill('1');
  pending=page.waitForResponse(r=>r.url().endsWith('/api/business/tasks/link-execution'));
  await dialog.getByRole('button',{name:'Link existing engineering work',exact:true}).click();
  response=await pending;
  if(![400,403,404,409].includes(response.status()))throw Error('Unbound execution did not fail closed: '+response.status());
  await dialog.getByRole('alert').waitFor();
  await page.screenshot({path:'reports/business-workspace-evidence/generation2/unbound-source-real.png'});
  const sourceError=await dialog.getByRole('alert').innerText();
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('dialog',{name:'Discard these changes?',exact:true}).getByRole('button',{name:'Discard my draft',exact:true}).click();
  await page.getByLabel('Area of work',{exact:true}).selectOption('');
  await page.getByLabel('Find a task',{exact:true}).fill('no-such-synthetic-task');
  await page.getByLabel('Find a task',{exact:true}).press('Enter');
  await page.getByText('No tasks match these filters.',{exact:true}).waitFor();
  await page.screenshot({path:'reports/business-workspace-evidence/generation2/no-results-real.png'});
  await page.getByRole('button',{name:'Clear filters',exact:true}).click();
  await page.getByRole('heading',{name:'Prepare the feedback summary · Synthetic',exact:true}).waitFor();
  return {synthetic:true,assignment:{taskId:task.id,ownerId:task.ownerId,assigneeId:task.assigneeId,reviewerId:task.reviewerId,revision:task.revision},revokedOwnerExcluded:true,websiteCount:website.tasks.length,sourceFailureStatus:response.status(),sourceError,personalOwnerCannotEntrust:true,searchEmptyAndReset:true};
}
