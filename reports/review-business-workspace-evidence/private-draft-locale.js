async page => {
  await page.getByRole('dialog').getByRole('button', {name: 'Close', exact: true}).click()
  await page.setViewportSize({width:1280, height:900})
  await page.getByRole('button', {name:'Refresh', exact:true}).click()
  await page.getByRole('button', {name:/Synthetic review: customer welcome brief/}).click()
  const dialog = page.getByRole('dialog', {name:'Synthetic review: customer welcome brief',exact:true})
  await dialog.getByText('Revision 5', {exact:true}).waitFor()
  await dialog.getByLabel('Add note', {exact:true}).fill('Synthetic PRIVATE note draft sentinel')
  await dialog.getByLabel('Review note', {exact:true}).fill('Synthetic PRIVATE review draft sentinel')
  await dialog.locator('summary').filter({hasText:/^Submit for review$/}).click()
  await dialog.getByLabel('Deliverable', {exact:true}).fill('Synthetic PRIVATE deliverable draft sentinel')
  await dialog.getByRole('button', {name:'Edit task',exact:true}).click()
  await dialog.getByLabel('Task title', {exact:true}).fill('Synthetic PRIVATE title draft sentinel')
  await dialog.getByLabel('Brief', {exact:true}).fill('Synthetic PRIVATE brief draft sentinel')
  await dialog.getByLabel('Due date', {exact:true}).fill('2026-12-31')
  const prefs = await page.context().newPage()
  await prefs.route('**/*',route => route.request().url().startsWith('http://127.0.0.1:4340/') ? route.continue() : route.abort())
  await prefs.routeWebSocket('**', ws=>ws.close())
  await prefs.goto('http://127.0.0.1:4340/business.html')
  await prefs.getByRole('heading',{name:'Give shared work a clear next step.',exact:true}).waitFor()
  const results=[]
  for (const [locale,width] of [['ar',390],['en',768],['ar',1280],['en',390]]) {
    await prefs.getByRole('combobox',{name:/^(Language|اللغة)$/}).selectOption(locale)
    await page.setViewportSize({width,height:900})
    await page.getByLabel(locale==='ar'?'وصف العمل':'Brief',{exact:true}).waitFor()
    const brief=await page.getByLabel(locale==='ar'?'وصف العمل':'Brief',{exact:true}).inputValue()
    const title=await page.getByLabel(locale==='ar'?'عنوان المهمة':'Task title',{exact:true}).inputValue()
    const date=await page.getByLabel(locale==='ar'?'تاريخ الاستحقاق':'Due date',{exact:true}).inputValue()
    const dimensions=await page.evaluate(()=>({width:innerWidth,documentWidth:document.documentElement.scrollWidth,dir:document.documentElement.dir}))
    if(brief!=='Synthetic PRIVATE brief draft sentinel'||title!=='Synthetic PRIVATE title draft sentinel'||date!=='2026-12-31') throw Error('Draft lost across actual other-tab locale change')
    results.push({locale,...dimensions,title,brief,date})
  }
  await prefs.close()
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click()
  const retained={note:await dialog.getByLabel('Add note',{exact:true}).inputValue(),review:await dialog.getByLabel('Review note',{exact:true}).inputValue(),deliverable:await dialog.getByLabel('Deliverable',{exact:true}).inputValue()}
  if(!Object.values(retained).every(s=>s.includes('Synthetic PRIVATE'))) throw Error('View draft lost')
  await page.keyboard.press('Escape')
  const discard=page.getByRole('dialog',{name:'Discard these changes?',exact:true})
  await discard.waitFor()
  await discard.getByRole('button',{name:'Keep editing',exact:true}).click()
  await dialog.getByLabel('Review note',{exact:true}).scrollIntoViewIfNeeded()
  await page.evaluate(async()=>{await document.fonts.ready;await new Promise(requestAnimationFrame);await new Promise(requestAnimationFrame)})
  await page.screenshot({path:'reports/review-business-workspace-evidence/private-drafts-retained-390.png'})
  const privateStored=await page.evaluate(()=>[...Object.values(localStorage),...Object.values(sessionStorage)].some(s=>s.includes('Synthetic PRIVATE')||s.includes('bdm_')))
  await page.keyboard.press('Escape')
  await discard.getByRole('button',{name:'Discard my draft',exact:true}).click()
  await page.getByRole('dialog').waitFor({state:'detached'})
  return {actualOtherTabLocale:true,metadata:results,retained,discardPrompt:true,keepEditingPreserved:true,privateStored,explicitDiscardClosed:true}
}
