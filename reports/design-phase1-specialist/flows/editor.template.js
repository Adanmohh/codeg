async (page) => {
  if (!page.url().startsWith("http://127.0.0.1:4327/")) throw Error("Owned fixture only")
  const capture = __CAPTURE__
  const scope = page.getByRole("region",{name:"Ops desk",exact:true})
  const cases=[], checks=[]
  const shot=async(name)=>{await page.screenshot({path:`reports/design-phase1-specialist/screenshots/${name}.png`});cases.push({name,raw:await capture(page)})}
  await scope.getByRole("button",{name:"Inbox",exact:true}).click()
  await scope.getByRole("button",{name:/Reader Open A real local thread/}).click()
  await scope.getByRole("heading",{name:"A real local thread",exact:true}).waitFor()
  await shot("second-thread-1280-dark")
  await scope.getByRole("button",{name:/Reader Open Synthetic locale review/}).click()
  await scope.getByRole("heading",{name:"Synthetic locale review",exact:true}).waitFor()
  const body="Bounded design draft: all text remains after validation."
  const values={To:"invalid-address",Cc:"design.cc@example.com","Bcc · hidden from other recipients":"design.bcc@example.com",Subject:"Design validation draft","Reply message":body}
  for(const [label,value] of Object.entries(values)) await scope.getByLabel(label,{exact:true}).fill(value)
  await scope.getByRole("button",{name:"Save draft",exact:true}).click()
  await scope.getByRole("alert").waitFor()
  const error=await scope.getByRole("alert").innerText()
  if(await scope.getByLabel("Reply message",{exact:true}).inputValue()!==body) throw Error("Validation lost draft")
  await shot("draft-invalid-1280-dark")
  checks.push({BC8:"real protected API validation retained draft",error})
  let dialogMessage=""
  page.once("dialog",async(dialog)=>{dialogMessage=dialog.message();await dialog.dismiss()})
  await scope.getByRole("button",{name:"Morning",exact:true}).focus()
  await page.keyboard.press("Enter")
  if(!dialogMessage.includes("Discard unsaved")) throw Error("No leave guard")
  if(await scope.getByLabel("Reply message",{exact:true}).inputValue()!==body) throw Error("Discard cancel lost draft")
  await shot("discard-cancel-keyboard")
  checks.push({BC9:true,dialogMessage,returnedFocus:await scope.getByRole("button",{name:"Morning",exact:true}).evaluate(e=>({focused:document.activeElement===e,visible:e.matches(":focus-visible"),outline:getComputedStyle(e).outline,shadow:getComputedStyle(e).boxShadow}))})
  await scope.getByLabel("To",{exact:true}).fill("reader@example.com")
  await scope.getByRole("button",{name:"Save draft",exact:true}).click()
  await scope.getByRole("status").filter({hasText:"Draft saved · revision 2"}).waitFor()
  await shot("draft-saved-1280-dark")
  await scope.getByRole("button",{name:"Private note",exact:true}).click()
  await scope.getByLabel("Private note · never emailed",{exact:true}).fill("Design private note · ملاحظة خاصة. Synthetic only.")
  await shot("private-note-before")
  await scope.getByRole("button",{name:"Save private note",exact:true}).click()
  await scope.getByRole("status").filter({hasText:"Private note saved"}).waitFor()
  await scope.locator('[aria-label="Conversation messages"]').getByText("Design private note · ملاحظة خاصة. Synthetic only.",{exact:true}).scrollIntoViewIfNeeded()
  await shot("private-note-after")
  checks.push({BC5:true,savedNoteSeparateFromDraft:true})
  await scope.getByRole("button",{name:"Approvals",exact:true}).click()
  await scope.getByRole("button",{name:/Re: Synthetic locale review Task/}).click()
  await scope.getByRole("heading",{name:/Stale/}).waitFor()
  const send=scope.getByRole("button",{name:"Approve and send reply",exact:true})
  if(await send.isEnabled()) throw Error("Stale send enabled")
  await page.setViewportSize({width:390,height:844});await page.keyboard.press("Escape")
  await shot("stale-after-draft-save-390-dark")
  checks.push({BC11:true,controlledDraftRevision:2,sendDisabled:true})
  const stats=await page.evaluate(async()=> (await fetch("/api/ops_design_fixture_stats",{headers:{Authorization:"Bearer ops-design-synthetic-operator"}})).json())
  if(stats.providerRequests!==4) throw Error("Unexpected provider request")
  checks.push({providerRequests:4})
  return {syntheticOnly:true,checks,cases}
}
